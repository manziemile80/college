import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface ExportMeta {
  title: string;
  period?: string;
  generatedBy?: string;
  summary?: string;
}

export interface ExportColumn {
  header: string;
  key: string;
}

function filename(title: string, extension: string): string {
  return `${title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${new Date().toISOString().slice(0, 10)}.${extension}`;
}

/** Excel-compatible CSV export (opens directly in Excel / LibreOffice). */
export function exportCsv(rows: Record<string, unknown>[], columns: ExportColumn[], meta: ExportMeta): void {
  const escape = (value: unknown) => `"${String(value ?? '').replace(/"/g, '""')}"`;
  const lines = [
    [meta.title],
    [meta.period || ''],
    [`Generated by: ${meta.generatedBy || 'System'}`],
    [`Generated on: ${new Date().toLocaleString()}`],
    ...(meta.summary ? [meta.summary] : []),
    [],
    columns.map((c) => c.header),
    ...rows.map((row) => columns.map((c) => escape(row[c.key]))),
  ];
  const csv = lines.map((line) => (Array.isArray(line) ? line.join(',') : line)).join('\r\n');
  const url = URL.createObjectURL(new Blob(['\uFEFF', csv], { type: 'text/csv;charset=utf-8;' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = filename(meta.title, 'csv');
  link.click();
  URL.revokeObjectURL(url);
}

/** PDF report/print output with the organisation header and report metadata. */
export function exportPdf(rows: Record<string, unknown>[], columns: ExportColumn[], meta: ExportMeta): void {
  const doc = new jsPDF({ orientation: columns.length > 6 ? 'landscape' : 'portrait', unit: 'mm', format: 'a4' });
  doc.setFontSize(16);
  doc.text('College De Rebero', 14, 16);
  doc.setFontSize(12);
  doc.text(meta.title, 14, 23);
  doc.setFontSize(9);
  doc.text(`Period: ${meta.period || 'All records'}`, 14, 29);
  doc.text(`Generated by: ${meta.generatedBy || 'System'} on ${new Date().toLocaleString()}`, 14, 34);
  if (meta.summary) doc.text(meta.summary, 14, 39);

  autoTable(doc, {
    startY: meta.summary ? 43 : 38,
    head: [columns.map((c) => c.header)],
    body: rows.map((row) => columns.map((c) => String(row[c.key] ?? ''))),
    styles: { fontSize: 8 },
    headStyles: { fillColor: [16, 185, 129] },
    alternateRowStyles: { fillColor: [245, 250, 247] },
  });
  doc.save(filename(meta.title, 'pdf'));
}
