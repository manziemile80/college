import * as React from "react";

type IconProps = React.HTMLAttributes<HTMLElement> & { className?: string };

const icon = (classes: string) => {
  const Icon = ({ className, ...props }: IconProps) => (
    <i className={["bi", classes, className || ""].join(" ").trim()} aria-hidden="true" {...props} />
  );
  Icon.displayName = classes;
  return Icon;
};

